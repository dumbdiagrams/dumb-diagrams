import { DIAGRAM_LIMITS, characterLength, utf8ByteLength } from "@dumb-diagrams/runtime/core";
import { parseDgmResult } from "@dumb-diagrams/runtime/dsl";
import { sanitizeSvgResult } from "@dumb-diagrams/runtime/render";

import type { LayoutEditingMode, Viewport } from "../model/types";

export type DocumentOrigin =
  | "fixture"
  | "new"
  | "import"
  | "example"
  | "recovery"
  | "duplicate"
  | "file";

export interface WorkspaceTab {
  id: string;
  source: string;
  /** The source used when this tab was first opened, kept for example resets. */
  initialSource: string;
  savedSource: string;
  filename?: string;
  /** A bounded render snapshot used only while the tab is in the recycle bin. */
  previewSvg?: string;
  origin: DocumentOrigin;
  layoutMode: LayoutEditingMode;
  viewport: Viewport;
  viewportCustomized: boolean;
}

export interface WorkspaceState {
  version: 1;
  tabs: WorkspaceTab[];
  activeTabId: string;
  recentlyClosed: WorkspaceTab[];
}

export interface WorkspaceModelOptions {
  initialSource: string;
  initialSavedSource?: string;
  initialOrigin?: DocumentOrigin;
  initialFilename?: string;
  initialViewport: Viewport;
  blankSource: string;
}

export const MAX_RECENTLY_CLOSED = 10;
export const MAX_RECYCLED_PREVIEW_BYTES = 96 * 1024;
export const MAX_WORKSPACE_TABS = 10;
export type WorkspacePreviewMap = Readonly<Record<string, string | undefined>>;

/**
 * Keep persisted previews limited to SVG generated by the renderer. The source
 * remains the recovery authority; this guard only protects the preview HTML
 * that is later inserted into the recycle-bin thumbnail.
 */
export function normalizeWorkspacePreview(value: unknown): string | undefined {
  if (typeof value !== "string" || utf8ByteLength(value) > MAX_RECYCLED_PREVIEW_BYTES) return undefined;
  // The renderer's strict attribute policy intentionally rejects external
  // references, while generated SVGs carry the inert SVG namespace URL.
  // Validate that namespace separately and sanitize the remaining markup.
  const namespace = value.match(/\s+xmlns=(['"])http:\/\/www\.w3\.org\/2000\/svg\1/i)?.[0];
  const sanitized = sanitizeSvgResult(namespace ? value.replace(namespace, "") : value);
  if (sanitized.isErr()) return undefined;
  const content = !namespace || /\bxmlns\s*=/i.test(sanitized.value.content)
    ? sanitized.value.content
    : sanitized.value.content.replace(/^\s*<svg\b/i, (tag) => `${tag}${namespace}`);
  return utf8ByteLength(content) <= MAX_RECYCLED_PREVIEW_BYTES ? content : undefined;
}

export function createWorkspaceTab(
  source: string,
  options: {
    initialSource?: string;
    savedSource?: string;
    filename?: string;
    origin?: DocumentOrigin;
    layoutMode?: LayoutEditingMode;
    viewport: Viewport;
    viewportCustomized?: boolean;
    id?: string;
  },
): WorkspaceTab {
  return {
    id: options.id ?? createTabId(),
    source,
    initialSource: options.initialSource ?? source,
    savedSource: options.savedSource ?? source,
    filename: options.filename,
    origin: options.origin ?? "new",
    layoutMode: options.layoutMode ?? "manual",
    viewport: { ...options.viewport },
    viewportCustomized: options.viewportCustomized ?? false,
  };
}

export function duplicateFilename(filename?: string): string | undefined {
  if (!filename) return undefined;
  const dot = filename.lastIndexOf(".");
  const stem = dot > 0 ? filename.slice(0, dot) : filename;
  const extension = dot > 0 ? filename.slice(dot) : ".dgm";
  return `${stem} copy${extension}`;
}

export function isTabDirty(tab: WorkspaceTab | undefined): boolean {
  return Boolean(tab && tab.source !== tab.savedSource);
}

export function isProtectedDefaultTab(tabs: WorkspaceTab[], blankSource: string, tabId = tabs[0]?.id): boolean {
  const tab = tabs.length === 1 ? tabs[0] : undefined;
  return Boolean(tab && tab.id === tabId && tab.origin === "new" && !tab.filename && tab.source === blankSource);
}

/** Tabs that can be discarded without offering recovery. */
export function isDisposableTab(tab: WorkspaceTab, blankSource: string): boolean {
  if (tab.origin === "new") {
    if (tab.source === blankSource) return true;
    // Empty drafts may have been serialized with a filename or formatting
    // changes. Keep intentionally renamed empty diagrams recoverable.
    const parsed = parseDgmResult(tab.source);
    if (parsed.isOk()) {
      const document = parsed.value;
      const empty = document.resources.length === 0 && document.groups.length === 0 &&
        document.edges.length === 0 && document.annotations.length === 0 &&
        (document.assets?.length ?? 0) === 0;
      const title = document.title?.trim().toLowerCase().replace(/[-_]+/g, " ").replace(/\s+/g, " ");
      if (empty && (!title || title === "untitled diagram")) return true;
    }
  }
  return (tab.origin === "fixture" || tab.origin === "example") &&
    tab.source === tab.initialSource && tab.source === tab.savedSource;
}

export function closeWorkspaceTabs(
  current: WorkspaceState,
  tabIds: string[],
  options: {
    preferredActiveTabId?: string;
    replacementTab?: WorkspaceTab;
    previewByTabId?: WorkspacePreviewMap;
    protectedBlankSource?: string;
  } = {},
): { state: WorkspaceState; closed: WorkspaceTab[] } {
  const closingIds = new Set(tabIds);
  if (options.protectedBlankSource !== undefined && isProtectedDefaultTab(current.tabs, options.protectedBlankSource) && closingIds.has(current.activeTabId)) return { state: current, closed: [] };
  const removed = current.tabs
    .filter((tab) => closingIds.has(tab.id))
    .map((tab) => {
      const previews = options.previewByTabId;
      if (!previews || !Object.prototype.hasOwnProperty.call(previews, tab.id)) return tab;
      const previewSvg = normalizeWorkspacePreview(previews[tab.id]);
      return previewSvg ? { ...tab, previewSvg } : omitWorkspacePreview(tab);
    });
  if (!removed.length) return { state: current, closed: [] };
  const archived = removed.filter((tab) => options.protectedBlankSource === undefined || !isDisposableTab(tab, options.protectedBlankSource));

  const tabs = current.tabs.filter((tab) => !closingIds.has(tab.id));
  if (!tabs.length && options.replacementTab) tabs.push(options.replacementTab);

  const closedActiveIndex = current.tabs.findIndex((tab) => tab.id === current.activeTabId);
  const activeTabId = options.preferredActiveTabId && tabs.some((tab) => tab.id === options.preferredActiveTabId)
    ? options.preferredActiveTabId
    : closingIds.has(current.activeTabId) && tabs.length > 0
      ? tabs[Math.max(0, Math.min(closedActiveIndex - 1, tabs.length - 1))]!.id
      : current.activeTabId;
  const closedIds = new Set(archived.map((tab) => tab.id));
  const recentlyClosed = [
    ...archived.slice().reverse(),
    ...current.recentlyClosed.filter((tab) => !closedIds.has(tab.id)),
  ].slice(0, MAX_RECENTLY_CLOSED);

  return {
    state: { ...current, tabs, activeTabId, recentlyClosed },
    // `closed` reports all removed tabs; only `recentlyClosed` is recoverable.
    closed: removed,
  };
}

export function restoreWorkspaceTab(current: WorkspaceState, tabId: string): WorkspaceState | null {
  if (current.tabs.length >= MAX_WORKSPACE_TABS) return null;
  const index = current.recentlyClosed.findIndex((tab) => tab.id === tabId);
  if (index < 0) return null;
  const restored = current.recentlyClosed[index]!;
  return {
    ...current,
    tabs: [...current.tabs, { ...restored, viewport: { ...restored.viewport } }],
    activeTabId: restored.id,
    recentlyClosed: current.recentlyClosed.filter((_, candidateIndex) => candidateIndex !== index),
  };
}

export function createWorkspaceState(options: WorkspaceModelOptions): WorkspaceState {
  const tab = createWorkspaceTab(options.initialSource, {
    initialSource: options.initialSource,
    savedSource: options.initialSavedSource ?? options.initialSource,
    filename: options.initialFilename,
    origin: options.initialOrigin ?? "fixture",
    viewport: options.initialViewport,
  });
  return { version: 1, tabs: [tab], activeTabId: tab.id, recentlyClosed: [] };
}

export function normalizeWorkspaceState(input: unknown): WorkspaceState | null {
  if (!input || typeof input !== "object") return null;
  const raw = input as Partial<WorkspaceState>;
  if (!Array.isArray(raw.tabs) || raw.tabs.length === 0) return null;

  const tabs = raw.tabs.slice(0, MAX_WORKSPACE_TABS)
    .map((tab) => normalizeTab(tab))
    .filter((tab): tab is WorkspaceTab => Boolean(tab));
  if (tabs.length === 0) return null;

  const activeTabId = tabs.some((tab) => tab.id === raw.activeTabId) ? String(raw.activeTabId) : tabs[0]!.id;
  const recentlyClosed = Array.isArray(raw.recentlyClosed)
    ? raw.recentlyClosed.slice(0, MAX_RECENTLY_CLOSED)
        .map((tab) => normalizeTab(tab))
        .filter((tab): tab is WorkspaceTab => Boolean(tab))
    : [];

  return { version: 1, tabs, activeTabId, recentlyClosed };
}

export function serializeWorkspace(state: WorkspaceState): string {
  const serialized = JSON.stringify(state);
  if (utf8ByteLength(serialized) <= DIAGRAM_LIMITS.workspaceBytes) return serialized;

  // A preview is an acceleration for recovery, never the recovery data. If
  // thumbnails would push the snapshot over the storage budget, retain all
  // source and tab metadata while dropping only the optional previews.
  return JSON.stringify({
    ...state,
    tabs: state.tabs.map(omitWorkspacePreview),
    recentlyClosed: state.recentlyClosed.map(omitWorkspacePreview),
  });
}

export function deserializeWorkspace(raw: string): WorkspaceState | null {
  if (utf8ByteLength(raw) > DIAGRAM_LIMITS.workspaceBytes) return null;
  try {
    return normalizeWorkspaceState(JSON.parse(raw));
  } catch {
    return null;
  }
}

function createTabId(): string {
  return globalThis.crypto?.randomUUID
    ? globalThis.crypto.randomUUID()
    : `tab-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function normalizeTab(input: unknown): WorkspaceTab | null {
  if (!input || typeof input !== "object") return null;
  const tab = input as Partial<WorkspaceTab>;
  if (typeof tab.id !== "string" || !tab.id || characterLength(tab.id) > DIAGRAM_LIMITS.idCharacters || typeof tab.source !== "string") return null;
  if (utf8ByteLength(tab.source) > DIAGRAM_LIMITS.sourceBytes) return null;
  if (typeof tab.initialSource === "string" && utf8ByteLength(tab.initialSource) > DIAGRAM_LIMITS.sourceBytes) return null;
  if (typeof tab.savedSource === "string" && utf8ByteLength(tab.savedSource) > DIAGRAM_LIMITS.sourceBytes) return null;
  const savedSource = typeof tab.savedSource === "string" ? tab.savedSource : tab.source;
  const origin = isDocumentOrigin(tab.origin) ? tab.origin : "new";
  const layoutMode = isLayoutEditingMode(tab.layoutMode) ? tab.layoutMode : "manual";
  const initialSource = typeof tab.initialSource === "string"
    ? tab.initialSource
    : origin === "example" ? savedSource : tab.source;
  const previewSvg = normalizeWorkspacePreview(tab.previewSvg);
  const viewport = tab.viewport;
  if (!viewport || !finiteCoordinate(viewport.panX) || !finiteCoordinate(viewport.panY) ||
      typeof viewport.zoom !== "number" || !Number.isFinite(viewport.zoom) || viewport.zoom <= 0 || viewport.zoom > 10) return null;
  return {
    id: tab.id,
    source: tab.source,
    initialSource,
    savedSource,
    filename: normalizeSourceFilename(typeof tab.filename === "string" ? tab.filename : undefined),
    ...(previewSvg ? { previewSvg } : {}),
    origin,
    layoutMode,
    viewport: { panX: viewport.panX, panY: viewport.panY, zoom: viewport.zoom },
    viewportCustomized: tab.viewportCustomized === true,
  };
}

function omitWorkspacePreview(tab: WorkspaceTab): WorkspaceTab {
  if (tab.previewSvg === undefined) return tab;
  const next = { ...tab };
  delete next.previewSvg;
  return next;
}

function normalizeSourceFilename(filename?: string): string | undefined {
  if (!filename) return undefined;
  if (characterLength(filename) > DIAGRAM_LIMITS.filenameCharacters) return undefined;
  const dot = filename.lastIndexOf(".");
  return dot > 0 ? `${filename.slice(0, dot)}.dgm` : filename;
}

function isDocumentOrigin(value: unknown): value is DocumentOrigin {
  return value === "fixture" || value === "new" || value === "import" || value === "example" || value === "recovery" || value === "duplicate" || value === "file";
}

function isLayoutEditingMode(value: unknown): value is LayoutEditingMode {
  return value === "manual" || value === "automatic";
}

function finiteCoordinate(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && Math.abs(value) <= DIAGRAM_LIMITS.coordinateMagnitude;
}

export function validateRestoredWorkspace(workspace: WorkspaceState): WorkspaceState | null {
  // Source is user-authored recovery data. Keep bounded syntax-invalid,
  // semantic-invalid, and unsafe-SVG drafts so the source editor can repair
  // them after reload; the renderer independently gates these values.
  const tabs = workspace.tabs.map(normalizeRestoredTab);
  if (!tabs.length) return null;
  const recentlyClosed = workspace.recentlyClosed.map(normalizeRestoredTab);
  const restored = {
    ...workspace,
    tabs,
    recentlyClosed,
    activeTabId: tabs.some((tab) => tab.id === workspace.activeTabId) ? workspace.activeTabId : tabs[0]!.id,
  };
  // IndexedDB returns objects directly, so enforce the same aggregate
  // envelope limit that serialized journal/fallback snapshots already have.
  return utf8ByteLength(serializeWorkspace(restored)) <= DIAGRAM_LIMITS.workspaceBytes ? restored : null;
}

function normalizeRestoredTab(tab: WorkspaceTab): WorkspaceTab {
  const previewSvg = normalizeWorkspacePreview(tab.previewSvg);
  return previewSvg ? { ...tab, previewSvg } : omitWorkspacePreview(tab);
}
