/**
 * Keep persisted previews limited to SVG generated by the renderer. The source
 * remains the recovery authority; this guard only protects the preview HTML
 * that is later inserted into the recycle-bin thumbnail.
 */
export function normalizeWorkspacePreview(value: unknown): string | undefined {
  if (typeof value !== "string" || utf8ByteLength(value) > MAX_RECYCLED_PREVIEW_BYTES) return undefined;
  if (!/^\s*<svg\b/i.test(value) || !/<\/svg>\s*$/i.test(value)) return undefined;
  if (/<\s*\/?\s*(?:script|foreignObject|iframe|object|embed)\b|<[^>]*\bon[a-z][\w:-]*\s*=|<[^>]*\b(?:href|xlink:href)\s*=\s*["'][^"']*(?:javascript:|data:)/i.test(value)) return undefined;
  return value;
}

export function createWorkspaceTab(
  source: string,
  options: {
    initialSource?: string;
    savedSource?: string;
    filename?: string;
    origin?: DocumentOrigin;
    viewport: Viewport;
    viewportCustomized?: boolean;
    id?: string;
  },
): WorkspaceTab {
  return {
    id: options.id ?? createTabId(),
    source,
    initialSource: options.initialSource ?? source,
    savedSource: options.savedSource ?? source,
    filename: options.filename,
    origin: options.origin ?? "new",
    viewport: { ...options.viewport },
    viewportCustomized: options.viewportCustomized ?? false,
  };
}

export function isTabDirty(tab: WorkspaceTab | undefined): boolean {
  return Boolean(tab && tab.source !== tab.savedSource);
}

export function isProtectedDefaultTab(tabs: WorkspaceTab[], blankSource: string, tabId = tabs[0]?.id): boolean {
  const tab = tabs.length === 1 ? tabs[0] : undefined;
  return Boolean(tab && tab.id === tabId && tab.origin === "new" && !tab.filename && tab.source === blankSource);
}

/** Tabs that can be discarded without offering recovery. */
export function isDisposableTab(tab: WorkspaceTab, blankSource: string): boolean {
  if (tab.origin === "new") {
    if (tab.source === blankSource) return true;
    // Empty drafts may have been serialized with a filename or formatting
    // changes. Keep intentionally renamed empty diagrams recoverable.
    try {
      const document = parseDgm(tab.source);
      const empty = document.resources.length === 0 && document.groups.length === 0 &&
        document.edges.length === 0 && document.annotations.length === 0 &&
        (document.assets?.length ?? 0) === 0;
      const title = document.title?.trim().toLowerCase().replace(/[-_]+/g, " ").replace(/\s+/g, " ");
      if (empty && (!title || title === "untitled diagram")) return true;
    } catch {
      // Invalid drafts remain recoverable.
    }
  }
  return (tab.origin === "fixture" || tab.origin === "example") &&
    tab.source === tab.initialSource && tab.source === tab.savedSource;
}

export function closeWorkspaceTabs(
  current: WorkspaceState,
  tabIds: string[],
  options: {
    preferredActiveTabId?: string;
    replacementTab?: WorkspaceTab;
    previewByTabId?: WorkspacePreviewMap;
    protectedBlankSource?: string;
  } = {},
): { state: WorkspaceState; closed: WorkspaceTab[] } {
  const closingIds = new Set(tabIds);
  if (options.protectedBlankSource !== undefined && isProtectedDefaultTab(current.tabs, options.protectedBlankSource) && closingIds.has(current.activeTabId)) return { state: current, closed: [] };
  const removed = current.tabs
    .filter((tab) => closingIds.has(tab.id))
    .map((tab) => {
      const previews = options.previewByTabId;
      if (!previews || !Object.prototype.hasOwnProperty.call(previews, tab.id)) return tab;
      const previewSvg = normalizeWorkspacePreview(previews[tab.id]);
      return previewSvg ? { ...tab, previewSvg } : omitWorkspacePreview(tab);
    });
  if (!removed.length) return { state: current, closed: [] };
  const archived = removed.filter((tab) => options.protectedBlankSource === undefined || !isDisposableTab(tab, options.protectedBlankSource));

  const tabs = current.tabs.filter((tab) => !closingIds.has(tab.id));
  if (!tabs.length && options.replacementTab) tabs.push(options.replacementTab);

  const closedActiveIndex = current.tabs.findIndex((tab) => tab.id === current.activeTabId);
  const activeTabId = options.preferredActiveTabId && tabs.some((tab) => tab.id === options.preferredActiveTabId)
    ? options.preferredActiveTabId
    : closingIds.has(current.activeTabId) && tabs.length > 0
      ? tabs[Math.max(0, Math.min(closedActiveIndex - 1, tabs.length - 1))]!.id
      : current.activeTabId;
  const closedIds = new Set(archived.map((tab) => tab.id));
  const recentlyClosed = [
    ...archived.slice().reverse(),
    ...current.recentlyClosed.filter((tab) => !closedIds.has(tab.id)),
  ].slice(0, MAX_RECENTLY_CLOSED);

  return {
    state: {
      ...current,
      tabs,
      activeTabId,
      recentlyClosed,
    },
    // `closed` reports all removed tabs; only `recentlyClosed` is recoverable.
    closed: removed,
  };
}

export function restoreWorkspaceTab(
  current: WorkspaceState,
  tabId: string,
): WorkspaceState | null {
  if (current.tabs.length >= MAX_WORKSPACE_TABS) return null;
  const index = current.recentlyClosed.findIndex((tab) => tab.id === tabId);
  if (index < 0) return null;
  const restored = current.recentlyClosed[index]!;
  return {
    ...current,
    tabs: [...current.tabs, { ...restored, viewport: { ...restored.viewport } }],
    activeTabId: restored.id,
    recentlyClosed: current.recentlyClosed.filter((_, candidateIndex) => candidateIndex !== index),
  };
}

export function createWorkspaceState(options: WorkspaceOptions): WorkspaceState {
  const tab = createWorkspaceTab(options.initialSource, {
    initialSource: options.initialSource,
    savedSource: options.initialSavedSource ?? options.initialSource,
    filename: options.initialFilename,
    origin: options.initialOrigin ?? "fixture",
    viewport: options.initialViewport,
  });
  return {
    version: 1,
    tabs: [tab],
    activeTabId: tab.id,
    recentlyClosed: [],
  };
}

export function normalizeWorkspaceState(input: unknown): WorkspaceState | null {
  if (!input || typeof input !== "object") return null;
  const raw = input as Partial<WorkspaceState>;
  if (!Array.isArray(raw.tabs) || raw.tabs.length === 0) return null;

  const tabs = raw.tabs.slice(0, MAX_WORKSPACE_TABS)
    .map((tab) => normalizeTab(tab))
    .filter((tab): tab is WorkspaceTab => Boolean(tab));
  if (tabs.length === 0) return null;

  const activeTabId = tabs.some((tab) => tab.id === raw.activeTabId)
    ? String(raw.activeTabId)
    : tabs[0]!.id;
  const recentlyClosed = Array.isArray(raw.recentlyClosed)
    ? raw.recentlyClosed.slice(0, MAX_RECENTLY_CLOSED)
        .map((tab) => normalizeTab(tab))
        .filter((tab): tab is WorkspaceTab => Boolean(tab))
    : [];

  return {
    version: 1,
    tabs,
    activeTabId,
    recentlyClosed,
  };
}

export function serializeWorkspace(state: WorkspaceState): string {
  const serialized = JSON.stringify(state);
  if (utf8ByteLength(serialized) <= DIAGRAM_LIMITS.workspaceBytes) return serialized;

  // A preview is an acceleration for recovery, never the recovery data. If
  // thumbnails would push the snapshot over the storage budget, retain all
  // source and tab metadata while dropping only the optional previews.
  return JSON.stringify({
    ...state,
    tabs: state.tabs.map(omitWorkspacePreview),
    recentlyClosed: state.recentlyClosed.map(omitWorkspacePreview),
  });
}

export function deserializeWorkspace(raw: string): WorkspaceState | null {
  if (utf8ByteLength(raw) > DIAGRAM_LIMITS.workspaceBytes) return null;
  try {
    return normalizeWorkspaceState(JSON.parse(raw));
  } catch {
    return null;
  }
}

export function useWorkspace(options: WorkspaceOptions) {
  const initialState = useMemo(() => createWorkspaceState(options), []);
  const [workspace, setWorkspace] = useState<WorkspaceState>(initialState);
  const workspaceRef = useRef(workspace);
  workspaceRef.current = workspace;
  const historiesRef = useRef(new Map<string, HistoryState>());
  const persistTimerRef = useRef<number | null>(null);
  const pendingPersistRef = useRef<WorkspaceState | null>(null);
  const persistQueueRef = useRef<Promise<void>>(Promise.resolve());
  const [historyVersion, setHistoryVersion] = useState(0);
  const [ready, setReady] = useState(false);
  const [persistenceWarning, setPersistenceWarning] = useState<string | null>(null);

  const reportPersistenceWarning = useCallback((warning: string | undefined) => {
    if (!warning) return;
    setPersistenceWarning((current) => current ?? warning);
  }, []);

  const touchHistory = useCallback(() => {
    setHistoryVersion((current) => current + 1);
  }, []);

  const ensureHistory = useCallback((tabId: string): HistoryState => {
    const existing = historiesRef.current.get(tabId);
    if (existing) return existing;
    const next = { past: [], future: [], transactionStart: null };
    historiesRef.current.set(tabId, next);
    return next;
  }, []);

  const flushPendingPersist = useCallback(() => {
    if (persistTimerRef.current !== null) {
      window.clearTimeout(persistTimerRef.current);
      persistTimerRef.current = null;
    }
    const next = pendingPersistRef.current;
    pendingPersistRef.current = null;
    if (!next) return;
    const serialized = serializeWorkspace(next);
    if (utf8ByteLength(serialized) > DIAGRAM_LIMITS.workspaceBytes) {
      reportPersistenceWarning("Workspace is too large to persist; edits remain local and may not survive reload.");
      return;
    }
    // Keep a synchronous write-ahead snapshot so an immediate reload cannot
    // outrun the debounced IndexedDB transaction (notably in WebKit).
    const journalResult = persistWorkspaceJournal(serialized);
    reportPersistenceWarning(journalResult.warning);
    persistQueueRef.current = persistQueueRef.current
      .catch(() => undefined)
      .then(() => persistWorkspace(next, serialized))
      .then((result) => reportPersistenceWarning(result.warning));
  }, [reportPersistenceWarning]);

  const updateWorkspace = useCallback(
    (change: (current: WorkspaceState) => WorkspaceState) => {
      // Keep the ref in lockstep with queued updates. Pointer gestures can
      // commit a preview and finish their transaction in the same event; a
      // functional React update may not run until after that event, leaving
      // endTransaction() looking at the pre-gesture source.
      const next = change(workspaceRef.current);
      workspaceRef.current = next;
      setWorkspace(next);
    },
    [],
  );

  useEffect(() => {
    let cancelled = false;

    void loadPersistedWorkspace().then((outcome) => {
      if (cancelled) return;
      reportPersistenceWarning(outcome.warning);
      const next = outcome.workspace ?? initialState;
      historiesRef.current = new Map(next.tabs.map((tab) => [tab.id, createHistory()]));
      workspaceRef.current = next;
      setWorkspace(next);
      setReady(true);
    });

    return () => {
      cancelled = true;
    };
  }, [initialState, reportPersistenceWarning]);

  useEffect(() => {
    if (!ready) return;
    pendingPersistRef.current = workspace;
    if (persistTimerRef.current !== null) {
      window.clearTimeout(persistTimerRef.current);
    }
    persistTimerRef.current = window.setTimeout(
      flushPendingPersist,
      WORKSPACE_PERSIST_DEBOUNCE_MS,
    );

    return () => {
      if (persistTimerRef.current !== null) {
        window.clearTimeout(persistTimerRef.current);
        persistTimerRef.current = null;
      }
    };
  }, [flushPendingPersist, ready, workspace]);

  useEffect(() => {
    const flushWhenHidden = () => {
      if (document.visibilityState === "hidden") flushPendingPersist();
    };
    window.addEventListener("pagehide", flushPendingPersist);
    document.addEventListener("visibilitychange", flushWhenHidden);
    return () => {
      window.removeEventListener("pagehide", flushPendingPersist);
      document.removeEventListener("visibilitychange", flushWhenHidden);
      flushPendingPersist();
    };
  }, [flushPendingPersist]);

  const activeTab = workspace.tabs.find((tab) => tab.id === workspace.activeTabId) ?? workspace.tabs[0]!;

  const replaceSource = useCallback(
    (source: string) => {
      if (utf8ByteLength(source) > DIAGRAM_LIMITS.sourceBytes) return;
      const activeId = workspaceRef.current.activeTabId;
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === activeId ? { ...tab, source } : tab),
      }));
    },
    [updateWorkspace],
  );

  const commitSource = useCallback(
    (source: string) => {
      if (utf8ByteLength(source) > DIAGRAM_LIMITS.sourceBytes) return;
      const currentState = workspaceRef.current;
      const active = currentState.tabs.find((tab) => tab.id === currentState.activeTabId);
      if (!active || active.source === source) return;
      const history = ensureHistory(active.id);
      history.past = [...history.past.slice(-(MAX_HISTORY - 1)), active.source];
      history.future = [];
      history.transactionStart = null;
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === active.id ? { ...tab, source } : tab),
      }));
      touchHistory();
    },
    [ensureHistory, touchHistory, updateWorkspace],
  );

  const resetTab = useCallback(
    (tabId: string, source: string, savedSource = source, metadata: Partial<Pick<WorkspaceTab, "filename" | "origin" | "initialSource">> = {}) => {
      const initialSource = metadata.initialSource ?? source;
      if (utf8ByteLength(source) > DIAGRAM_LIMITS.sourceBytes ||
          utf8ByteLength(savedSource) > DIAGRAM_LIMITS.sourceBytes ||
          utf8ByteLength(initialSource) > DIAGRAM_LIMITS.sourceBytes) return;
      if (!workspaceRef.current.tabs.some((tab) => tab.id === tabId)) return;
      historiesRef.current.set(tabId, createHistory());
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === tabId
          ? { ...tab, source, initialSource, savedSource, ...metadata }
          : tab),
      }));
      touchHistory();
    },
    [touchHistory, updateWorkspace],
  );

  const resetActive = useCallback(
    (source: string, savedSource = source, metadata: Partial<Pick<WorkspaceTab, "filename" | "origin" | "initialSource">> = {}) => {
      resetTab(workspaceRef.current.activeTabId, source, savedSource, metadata);
    },
    [resetTab],
  );

  const beginTransaction = useCallback(() => {
    const state = workspaceRef.current;
    const tab = state.tabs.find((candidate) => candidate.id === state.activeTabId);
    if (!tab) return;
    ensureHistory(tab.id).transactionStart = tab.source;
  }, [ensureHistory]);

  const endTransaction = useCallback(() => {
    const state = workspaceRef.current;
    const tab = state.tabs.find((candidate) => candidate.id === state.activeTabId);
    if (!tab) return;
    const history = ensureHistory(tab.id);
    const start = history.transactionStart;
    history.transactionStart = null;
    if (!start || start === tab.source) return;
    history.past = [...history.past.slice(-(MAX_HISTORY - 1)), start];
    history.future = [];
    touchHistory();
  }, [ensureHistory, touchHistory]);

  const undo = useCallback(() => {
    const state = workspaceRef.current;
    const tab = state.tabs.find((candidate) => candidate.id === state.activeTabId);
    if (!tab) return;
    const history = ensureHistory(tab.id);
    const previous = history.past.pop();
    if (previous === undefined) return;
    history.future.unshift(tab.source);
    history.transactionStart = null;
    updateWorkspace((current) => ({
      ...current,
      tabs: current.tabs.map((candidate) => candidate.id === tab.id ? { ...candidate, source: previous } : candidate),
    }));
    touchHistory();
  }, [ensureHistory, touchHistory, updateWorkspace]);

  const redo = useCallback(() => {
    const state = workspaceRef.current;
    const tab = state.tabs.find((candidate) => candidate.id === state.activeTabId);
    if (!tab) return;
    const history = ensureHistory(tab.id);
    const next = history.future.shift();
    if (next === undefined) return;
    history.past.push(tab.source);
    history.transactionStart = null;
    updateWorkspace((current) => ({
      ...current,
      tabs: current.tabs.map((candidate) => candidate.id === tab.id ? { ...candidate, source: next } : candidate),
    }));
    touchHistory();
  }, [ensureHistory, touchHistory, updateWorkspace]);

  const setActiveTab = useCallback(
    (tabId: string) => {
      if (!workspaceRef.current.tabs.some((tab) => tab.id === tabId)) return;
      updateWorkspace((current) => ({ ...current, activeTabId: tabId }));
    },
    [updateWorkspace],
  );

  const reorderTabs = useCallback(
    (tabId: string, targetTabId: string) => {
      if (tabId === targetTabId) return;
      updateWorkspace((current) => {
        const fromIndex = current.tabs.findIndex((tab) => tab.id === tabId);
        const targetIndex = current.tabs.findIndex((tab) => tab.id === targetTabId);
        if (fromIndex < 0 || targetIndex < 0) return current;
        const tabs = [...current.tabs];
        const [moved] = tabs.splice(fromIndex, 1);
        tabs.splice(tabs.findIndex((tab) => tab.id === targetTabId), 0, moved!);
        return { ...current, tabs };
      });
    },
    [updateWorkspace],
  );

  const openTab = useCallback(
    (source: string, tabOptions: Partial<Pick<WorkspaceTab, "initialSource" | "savedSource" | "filename" | "origin" | "viewport">> = {}) => {
      if (utf8ByteLength(source) > DIAGRAM_LIMITS.sourceBytes ||
          (tabOptions.initialSource !== undefined && utf8ByteLength(tabOptions.initialSource) > DIAGRAM_LIMITS.sourceBytes) ||
          (tabOptions.savedSource !== undefined && utf8ByteLength(tabOptions.savedSource) > DIAGRAM_LIMITS.sourceBytes)) return null;
      if (workspaceRef.current.tabs.length >= MAX_WORKSPACE_TABS) return null;
      const tab = createWorkspaceTab(source, {
        initialSource: tabOptions.initialSource ?? source,
        savedSource: tabOptions.savedSource ?? source,
        filename: tabOptions.filename,
        origin: tabOptions.origin ?? "new",
        viewport: tabOptions.viewport ?? options.initialViewport,
      });
      historiesRef.current.set(tab.id, createHistory());
      updateWorkspace((current) => ({
        ...current,
        tabs: [...current.tabs, tab],
        activeTabId: tab.id,
      }));
      return tab.id;
    },
    [options.initialViewport, updateWorkspace],
  );

  const newTab = useCallback(() => openTab(options.blankSource, { origin: "new" }), [openTab, options.blankSource]);

  const closeTabs = useCallback(
    (tabIds: string[], preferredActiveTabId?: string, previewByTabId?: WorkspacePreviewMap) => {
      const current = workspaceRef.current;
      const closesEveryTab = tabIds.length > 0 && current.tabs.every((tab) => tabIds.includes(tab.id));
      const replacementTab = closesEveryTab
        ? createWorkspaceTab(options.blankSource, {
            origin: "new",
            viewport: options.initialViewport,
          })
        : undefined;
      const result = closeWorkspaceTabs(current, tabIds, {
        preferredActiveTabId,
        replacementTab,
        previewByTabId,
        protectedBlankSource: options.blankSource,
      });
      if (!result.closed.length) return 0;
      if (replacementTab) historiesRef.current.set(replacementTab.id, createHistory());
      result.closed.forEach((tab) => historiesRef.current.delete(tab.id));
      updateWorkspace(() => result.state);
      return result.closed.length;
    },
    [options.blankSource, options.initialViewport, updateWorkspace],
  );

  const closeTab = useCallback(
    (tabId = workspaceRef.current.activeTabId, previewByTabId?: WorkspacePreviewMap) => {
      return closeTabs([tabId], undefined, previewByTabId);
    },
    [closeTabs],
  );

  const closeAllTabs = useCallback(
    (previewByTabId?: WorkspacePreviewMap) => closeTabs(workspaceRef.current.tabs.map((tab) => tab.id), undefined, previewByTabId),
    [closeTabs],
  );

  const closeTabsToRight = useCallback(
    (tabId: string, previewByTabId?: WorkspacePreviewMap) => {
      const current = workspaceRef.current;
      const index = current.tabs.findIndex((tab) => tab.id === tabId);
      if (index < 0) return 0;
      return closeTabs(current.tabs.slice(index + 1).map((tab) => tab.id), tabId, previewByTabId);
    },
    [closeTabs],
  );

  const restoreClosed = useCallback((tabId = workspaceRef.current.recentlyClosed[0]?.id) => {
    const current = workspaceRef.current;
    if (!tabId) return false;
    const next = restoreWorkspaceTab(current, tabId);
    if (!next) return false;
    const restored = next.tabs[next.tabs.length - 1]!;
    historiesRef.current.set(restored.id, createHistory());
    updateWorkspace(() => next);
    return true;
  }, [updateWorkspace]);

  const reopenClosed = useCallback(() => restoreClosed(), [restoreClosed]);

  const removeClosed = useCallback((tabId: string) => {
    const current = workspaceRef.current;
    if (!current.recentlyClosed.some((tab) => tab.id === tabId)) return false;
    updateWorkspace((state) => ({
      ...state,
      recentlyClosed: state.recentlyClosed.filter((tab) => tab.id !== tabId),
    }));
    return true;
  }, [updateWorkspace]);

  const clearRecentlyClosed = useCallback(() => {
    if (!workspaceRef.current.recentlyClosed.length) return false;
    updateWorkspace((state) => ({ ...state, recentlyClosed: [] }));
    return true;
  }, [updateWorkspace]);

  const duplicateTab = useCallback(
    (tabId = workspaceRef.current.activeTabId) => {
      if (workspaceRef.current.tabs.length >= MAX_WORKSPACE_TABS) return null;
      const sourceTab = workspaceRef.current.tabs.find((tab) => tab.id === tabId);
      if (!sourceTab) return null;
      const duplicate = createWorkspaceTab(sourceTab.source, {
        savedSource: sourceTab.savedSource,
        filename: duplicateFilename(sourceTab.filename),
        origin: "duplicate",
        viewport: sourceTab.viewport,
        viewportCustomized: sourceTab.viewportCustomized,
      });
      historiesRef.current.set(duplicate.id, createHistory());
      updateWorkspace((current) => ({
        ...current,
        tabs: [...current.tabs, duplicate],
        activeTabId: duplicate.id,
      }));
      return duplicate.id;
    },
    [updateWorkspace],
  );

  const updateViewport = useCallback(
    (viewport: Viewport, options: { userInitiated?: boolean } = {}) => {
      const activeId = workspaceRef.current.activeTabId;
      const userInitiated = options.userInitiated ?? true;
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === activeId
          ? {
              ...tab,
              viewport: { ...viewport },
              viewportCustomized: userInitiated ? true : tab.viewportCustomized,
            }
          : tab),
      }));
    },
    [updateWorkspace],
  );

  const markSaved = useCallback(
    (source = workspaceRef.current.tabs.find((tab) => tab.id === workspaceRef.current.activeTabId)?.source ?? "", filename?: string) => {
      const activeId = workspaceRef.current.activeTabId;
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === activeId
          ? { ...tab, savedSource: source, ...(filename === undefined ? {} : { filename }) }
          : tab),
      }));
    },
    [updateWorkspace],
  );

  const markTabSaved = useCallback(
    (tabId: string, source: string, filename?: string) => {
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === tabId
          ? { ...tab, savedSource: source, ...(filename === undefined ? {} : { filename }) }
          : tab),
      }));
    },
    [updateWorkspace],
  );

  const setTabFilename = useCallback(
    (tabId: string, filename?: string) => {
      updateWorkspace((current) => ({
        ...current,
        tabs: current.tabs.map((tab) => tab.id === tabId
          ? { ...tab, filename }
          : tab),
      }));
    },
    [updateWorkspace],
  );

  const canUndo = (historyVersion >= 0 && ensureHistory(activeTab.id).past.length > 0);
  const canRedo = (historyVersion >= 0 && ensureHistory(activeTab.id).future.length > 0);

  return {
    ready,
    tabs: workspace.tabs,
    activeTab,
    activeTabId: workspace.activeTabId,
    recentlyClosed: workspace.recentlyClosed,
    source: activeTab.source,
    viewport: activeTab.viewport,
    replaceSource,
    commitSource,
    resetTab,
    resetActive,
    beginTransaction,
    endTransaction,
    undo,
    redo,
    canUndo,
    canRedo,
    setActiveTab,
    reorderTabs,
    openTab,
    newTab,
    closeTab,
    closeAllTabs,
    closeTabsToRight,
    reopenClosed,
    restoreClosed,
    removeClosed,
    clearRecentlyClosed,
    duplicateTab,
    updateViewport,
    markSaved,
    markTabSaved,
    setTabFilename,
    persistenceWarning,
  };
}

function createHistory(): HistoryState {
  return { past: [], future: [], transactionStart: null };
}

function createTabId(): string {
  return globalThis.crypto?.randomUUID
    ? globalThis.crypto.randomUUID()
    : `tab-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function duplicateFilename(filename?: string): string | undefined {
  if (!filename) return undefined;
  const dot = filename.lastIndexOf(".");
  const stem = dot > 0 ? filename.slice(0, dot) : filename;
  const extension = dot > 0 ? filename.slice(dot) : ".dgm";
  return `${stem} copy${extension}`;
}

function normalizeTab(input: unknown): WorkspaceTab | null {
  if (!input || typeof input !== "object") return null;
  const tab = input as Partial<WorkspaceTab>;
  if (typeof tab.id !== "string" || !tab.id || characterLength(tab.id) > DIAGRAM_LIMITS.idCharacters || typeof tab.source !== "string") return null;
  if (utf8ByteLength(tab.source) > DIAGRAM_LIMITS.sourceBytes) return null;
  if (typeof tab.initialSource === "string" && utf8ByteLength(tab.initialSource) > DIAGRAM_LIMITS.sourceBytes) return null;
  if (typeof tab.savedSource === "string" && utf8ByteLength(tab.savedSource) > DIAGRAM_LIMITS.sourceBytes) return null;
  const savedSource = typeof tab.savedSource === "string" ? tab.savedSource : tab.source;
  const origin = isDocumentOrigin(tab.origin) ? tab.origin : "new";
  const initialSource = typeof tab.initialSource === "string"
    ? tab.initialSource
    : origin === "example" ? savedSource : tab.source;
  const previewSvg = normalizeWorkspacePreview(tab.previewSvg);
  const viewport = tab.viewport;
  if (!viewport || !finiteCoordinate(viewport.panX) || !finiteCoordinate(viewport.panY) ||
      typeof viewport.zoom !== "number" || !Number.isFinite(viewport.zoom) || viewport.zoom <= 0 || viewport.zoom > 10) {
    return null;
  }
  return {
    id: tab.id,
    source: tab.source,
    initialSource,
    savedSource,
    filename: normalizeSourceFilename(typeof tab.filename === "string" ? tab.filename : undefined),
    ...(previewSvg ? { previewSvg } : {}),
    origin,
    viewport: { panX: viewport.panX, panY: viewport.panY, zoom: viewport.zoom },
    viewportCustomized: tab.viewportCustomized === true,
  };
}

function omitWorkspacePreview(tab: WorkspaceTab): WorkspaceTab {
  if (tab.previewSvg === undefined) return tab;
  const next = { ...tab };
  delete next.previewSvg;
  return next;
}

function normalizeSourceFilename(filename?: string): string | undefined {
  if (!filename) return undefined;
  if (characterLength(filename) > DIAGRAM_LIMITS.filenameCharacters) return undefined;
  const dot = filename.lastIndexOf(".");
  return dot > 0 ? `${filename.slice(0, dot)}.dgm` : filename;
}

function isDocumentOrigin(value: unknown): value is DocumentOrigin {
  return value === "fixture" || value === "new" || value === "import" || value === "example" || value === "recovery" || value === "duplicate" || value === "file";
}

async function loadPersistedWorkspace(): Promise<WorkspaceLoadOutcome> {
  const warnings: string[] = [];
  try {
    const raw = localStorage.getItem(PENDING_WORKSPACE_KEY) ?? "";
    const normalized = deserializeWorkspace(raw);
    const validated = normalized ? validateRestoredWorkspace(normalized) : null;
    if (validated) return { status: "ok", workspace: validated };
    if (raw) warnings.push("The latest workspace recovery snapshot was unreadable.");
  } catch {
    warnings.push("Workspace recovery storage is unavailable; trying other local storage.");
  }
  try {
    const db = await openDatabase();
    try {
      const value = await readWorkspaceValue(db);
      const normalized = normalizeWorkspaceState(value);
      const validated = normalized ? validateRestoredWorkspace(normalized) : null;
      if (validated) return { status: warnings.length ? "degraded" : "ok", workspace: validated, warning: warnings[0] };
      if (value !== undefined) warnings.push("The stored workspace could not be restored; starting with a local workspace.");
    } finally {
      db.close();
    }
  } catch {
    warnings.push("IndexedDB workspace persistence is unavailable; trying recovery storage.");
  }
  try {
    const raw = localStorage.getItem(FALLBACK_KEY) ?? "";
    const normalized = deserializeWorkspace(raw);
    const validated = normalized ? validateRestoredWorkspace(normalized) : null;
    if (raw && !validated) warnings.push("The fallback workspace could not be restored; starting with a local workspace.");
    return {
      status: warnings.length ? "degraded" : "ok",
      workspace: validated,
      warning: warnings[0],
    };
  } catch {
    warnings.push("Local workspace persistence is unavailable; edits may not survive reload.");
    return {
      status: "degraded",
      workspace: null,
      warning: warnings[0],
    };
  }
}

function persistWorkspaceJournal(serialized: string): WorkspacePersistenceOutcome {
  try {
    localStorage.setItem(PENDING_WORKSPACE_KEY, serialized);
    return { status: "ok" };
  } catch {
    try {
      localStorage.removeItem(PENDING_WORKSPACE_KEY);
    } catch {
      // Storage may be completely disabled; the queued IndexedDB write still runs.
    }
    return {
      status: "degraded",
      warning: "Workspace recovery snapshot could not be written; edits may not survive an immediate reload.",
    };
  }
}

async function persistWorkspace(workspace: WorkspaceState, serialized: string): Promise<WorkspacePersistenceOutcome> {
  try {
    const db = await openDatabase();
    try {
      await writeWorkspaceValue(db, workspace);
    } finally {
      db.close();
    }
    try {
      // A later edit may already have replaced the journal while this queued
      // write was in flight. Only clear the snapshot that just reached disk.
      if (localStorage.getItem(PENDING_WORKSPACE_KEY) === serialized) {
        localStorage.removeItem(PENDING_WORKSPACE_KEY);
      }
    } catch {
      // A valid journal can safely remain if storage becomes unavailable.
    }
    return { status: "ok" };
  } catch {
    return {
      status: "degraded",
      warning: "Workspace persistence failed; edits remain local and may not survive reload.",
    };
  }
}

function finiteCoordinate(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && Math.abs(value) <= DIAGRAM_LIMITS.coordinateMagnitude;
}

function validateRestoredWorkspace(workspace: WorkspaceState): WorkspaceState | null {
  const valid = (tab: WorkspaceTab) => {
    try {
      const doc = parseDgm(tab.source);
      if (hasErrors(validateDocument(doc, getCatalogMap(), { enforceCatalogRules: false }))) return false;
      for (const asset of doc.assets ?? []) sanitizeSvg(asset.content);
      return true;
    } catch {
      return false;
    }
  };
  const tabs = workspace.tabs.filter(valid);
  if (!tabs.length) return null;
  const recentlyClosed = workspace.recentlyClosed.filter(valid);
  return {
    ...workspace,
    tabs,
    recentlyClosed,
    activeTabId: tabs.some((tab) => tab.id === workspace.activeTabId) ? workspace.activeTabId : tabs[0]!.id,
  };
}

function openDatabase(): Promise<IDBDatabase> {
  if (typeof indexedDB === "undefined") return Promise.reject(new Error("IndexedDB is unavailable."));
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);
    request.onupgradeneeded = () => {
      request.result.createObjectStore(STORE_NAME);
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error ?? new Error("Unable to open workspace storage."));
  });
}

function readWorkspaceValue(db: IDBDatabase): Promise<unknown> {
  return new Promise((resolve, reject) => {
    const transaction = db.transaction(STORE_NAME, "readonly");
    const request = transaction.objectStore(STORE_NAME).get(WORKSPACE_KEY);
    let value: unknown;
    request.onsuccess = () => {
      value = request.result;
    };
    request.onerror = () => reject(request.error ?? new Error("Workspace read failed."));
    transaction.oncomplete = () => resolve(value);
    transaction.onerror = () => reject(transaction.error ?? new Error("Workspace read transaction failed."));
    transaction.onabort = () => reject(transaction.error ?? new Error("Workspace read transaction aborted."));
  });
}

function writeWorkspaceValue(db: IDBDatabase, workspace: WorkspaceState): Promise<void> {
  return new Promise((resolve, reject) => {
    const transaction = db.transaction(STORE_NAME, "readwrite");
    try {
      transaction.objectStore(STORE_NAME).put(workspace, WORKSPACE_KEY);
    } catch (error) {
      reject(error);
      return;
    }
    transaction.oncomplete = () => resolve();
    transaction.onerror = () => reject(transaction.error ?? new Error("Workspace write transaction failed."));
    transaction.onabort = () => reject(transaction.error ?? new Error("Workspace write transaction aborted."));
  });
}
